# ---------------- self-attention ----------------
class Head(nn.Module):
    """un singur cap de self-attention"""

    def __init__(self, head_size):
        super().__init__()
        self.key = nn.Linear(n_embed, head_size, bias=False)
        self.query = nn.Linear(n_embed, head_size, bias=False)
        self.value = nn.Linear(n_embed, head_size, bias=False)
        self.register_buffer('tril', torch.tril(torch.ones(block_size, block_size)))  # masca, salvată în model
        self.dropout = nn.Dropout(dropout)  # oprește aleator o parte din legături, împotriva memorării

    def forward(self, x):
        B, T, C = x.shape
        k = self.key(x)      # (B, T, head_size)  "ce sunt eu"
        q = self.query(x)    # (B, T, head_size)  "ce caut"
        wei = q @ k.transpose(-2, -1) * k.shape[-1]**-0.5   # (B, T, T) scorurile, împărțite la radical din head_size
        wei = wei.masked_fill(self.tril[:T, :T] == 0, float('-inf'))  # blocăm viitorul
        wei = F.softmax(wei, dim=-1)                                  # scoruri -> procente
        wei = self.dropout(wei)
        v = self.value(x)    # (B, T, head_size)  "ce dau mai departe"
        out = wei @ v        # (B, T, head_size)  amestecăm informația din trecut
        return out

# ---------------- multi-head attention ----------------
class MultiHeadAttention(nn.Module):
    """mai multe capete de atenție în paralel; rezultatele lor se lipesc"""

    def __init__(self, num_heads, head_size):
        super().__init__()
        self.heads = nn.ModuleList([Head(head_size) for _ in range(num_heads)])  # ModuleList: ca PyTorch să le antreneze
        self.proj = nn.Linear(head_size * num_heads, n_embed)  # W^O: amestecă ce au aflat capetele
        self.dropout = nn.Dropout(dropout)

    def forward(self, x):
        out = torch.cat([h(x) for h in self.heads], dim=-1)  # Concat: (B, T, num_heads * head_size)
        out = self.dropout(self.proj(out))                   # (B, T, n_embed)
        return out

# ---------------- feed-forward ----------------
class FeedForward(nn.Module):
    """după ce literele au "vorbit", fiecare "se gândește" singură la ce a aflat"""

    def __init__(self, n_embed):
        super().__init__()
        self.net = nn.Sequential(
            nn.Linear(n_embed, 4 * n_embed),   # mărește vectorul de 4 ori, ca în articol
            nn.ReLU(),                         # păstrează pozitivele, pune 0 la negative
            nn.Linear(4 * n_embed, n_embed),   # îl readuce la mărimea inițială
            nn.Dropout(dropout),
        )

    def forward(self, x):
        return self.net(x)  # se aplică pe fiecare poziție separat

# ---------------- bloc Transformer ----------------
class Block(nn.Module):
    """un bloc: comunicare (atenție), apoi calcul (feed-forward)"""

    def __init__(self, n_embed, n_head):
        super().__init__()
        head_size = n_embed // n_head                      # d_k = d_model / h  (32 / 4 = 8)
        self.sa = MultiHeadAttention(n_head, head_size)
        self.ffwd = FeedForward(n_embed)
        self.ln1 = nn.LayerNorm(n_embed)                   # normalizare înainte de atenție
        self.ln2 = nn.LayerNorm(n_embed)                   # normalizare înainte de feed-forward

    def forward(self, x):
        x = x + self.sa(self.ln1(x))     # conexiune reziduală: adaugă peste ce exista
        x = x + self.ffwd(self.ln2(x))   # conexiune reziduală
        return x

class BigramLanguageModel(nn.Module):  # numele a rămas din video; acum e un GPT mic

    def __init__(self, vocab_size):
        super().__init__()
        self.token_embedding_table = nn.Embedding(vocab_size, n_embed)
        self.position_embedding_table=nn.Embedding(block_size,n_embed)
        self.blocks = nn.Sequential(*[Block(n_embed, n_head=n_head) for _ in range(n_layer)])  # n_layer blocuri la rând
        self.ln_f = nn.LayerNorm(n_embed)  # normalizare finală
        self.lm_head=nn.Linear(n_embed, vocab_size)
    def forward(self, idx, targets=None):
        B,T=idx.shape
        tok_emb = self.token_embedding_table(idx)  # (B, T, n_embed) ce literă e
        pos_emb = self.position_embedding_table(torch.arange(T, device=device))  # (T, n_embed) pe ce poziție e
        x=tok_emb+ pos_emb  # (B, T, n_embed) litera + poziția ei
        x = self.blocks(x)  # (B, T, n_embed) trece prin toate blocurile
        x = self.ln_f(x)    # (B, T, n_embed)
        logits=self.lm_head(x)  # (B, T, vocab_size)
        if targets is None:
            loss = None
        else:
            B, T, C = logits.shape
            logits = logits.view(B*T, C)
            targets = targets.view(B*T)
            loss = F.cross_entropy(logits, targets)
        return logits, loss

    def generate(self, idx, max_new_tokens):
        for _ in range(max_new_tokens):
            idx_cond = idx[:, -block_size:]  # doar ultimele block_size litere, ca să nu depășim tabelul de poziții
            logits, loss = self(idx_cond)
            logits = logits[:, -1, :]
            probs = F.softmax(logits, dim=-1)
            idx_next = torch.multinomial(probs, num_samples=1)
            idx = torch.cat((idx, idx_next), dim=1)
        return idx

